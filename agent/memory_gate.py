"""Признак «в сообщении есть что запоминать о пользователе».

Извлечение памяти — отдельный вызов модели после каждого ответа, и на
слабой машине он стоит 2,2-10,7 с. Вопрос по регламенту («в какой срок
проводится расследование») сведений о пользователе не содержит вовсе,
поэтому такой вызов там — чистая трата времени.

Хуже того, он не просто бесполезен, а вреден. Замер на четырёх подряд
вопросах по регламентам дал три записи в памяти, и все три — журнал
заданных вопросов: «Пользователь интересуется сроком расследования
несчастного случая», «Пользователь задавал вопрос о частоте проверки
огнетушителей». Настоящих фактов о человеке при этом не появилось ни
одного. Предел памяти — 15 записей, так что за одну рабочую сессию имя и
должность вытесняются журналом вопросов, а ассистент отвечает о
пользователе именно по этому блоку.

Отбор нарочно грубый и работает по местоимениям и глаголам первого лица.
Ошибка в сторону лишнего вызова безобидна: «какие СИЗ мне положены»
местоимение содержит, вызов пройдёт впустую — ровно как сейчас происходит
на каждом сообщении. Ошибка в другую сторону дороже, поэтому список
маркеров лучше держать широким.
"""

from __future__ import annotations

import re

#: Маркеры того, что человек говорит о себе.
#:
#: Разделены на группы по смыслу, чтобы список было видно и легко
#: пополнять: местоимения первого лица, глаголы представления и
#: принадлежности, прямые просьбы запомнить.
_MARKERS = (
    # местоимения первого лица
    r"\bя\b",
    r"\bмне\b",
    r"\bменя\b",
    r"\bмной\b",
    r"\bмо[йяеё]\b",
    r"\bмои\b",
    r"\bмоего\b",
    r"\bмоей\b",
    r"\bмоих\b",
    r"\bмы\b",
    r"\bнам\b",
    r"\bнас\b",
    r"\bнаш\w*\b",
    r"\bу\s+меня\b",
    # представление и принадлежность
    r"\bзовут\b",
    r"\bработаю\b",
    r"\bтружусь\b",
    r"\bдолжност\w*\b",
    r"\bя\s+из\b",
    # прямая просьба
    r"\bзапомни\w*\b",
    r"\bзаполни\s+профил\w*\b",
    r"\bне\s+забуд\w*\b",
)

_PATTERN = re.compile("|".join(_MARKERS), re.IGNORECASE)


def mentions_user(text: str) -> bool:
    """Проверяет, говорит ли сообщение о самом пользователе.

    Args:
        text: Текст сообщения пользователя.

    Returns:
        bool: ``True``, если в сообщении есть маркеры первого лица или
        прямая просьба запомнить, то есть извлечение памяти осмысленно.
    """
    if not text or not text.strip():
        return False
    return bool(_PATTERN.search(text.replace("ё", "е")))


def worth_extracting(messages: list) -> bool:
    """Решает, нужно ли запускать извлечение памяти.

    Args:
        messages: Сообщения диалога; проверяются только реплики человека.

    Returns:
        bool: ``True``, если хотя бы в одной из двух последних реплик
        пользователя есть сведения о нём самом. Две, а не одна, потому что
        человек часто представляется отдельным сообщением, а следующим уже
        задаёт вопрос — и к моменту извлечения последняя реплика окажется
        безличной.
    """
    human_texts: list[str] = []
    for message in reversed(messages):
        role = getattr(message, "type", None) or (
            message.get("role") if isinstance(message, dict) else None
        )
        if role not in ("human", "user"):
            continue
        content = getattr(message, "content", None)
        if content is None and isinstance(message, dict):
            content = message.get("content")
        human_texts.append(str(content or ""))
        if len(human_texts) == 2:
            break

    return any(mentions_user(text) for text in human_texts)
