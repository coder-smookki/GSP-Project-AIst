"""Грейдер релевантности: отсев фрагментов перед генерацией.

**Выключен по умолчанию, потому что на этом корпусе не даёт ничего.**
Ниже — замер, а не соображения; модуль оставлен как рабочая заготовка на
случай другого корпуса или другой модели, а не как часть основного пути.

Проверка на живом стенде (qwen3:8b, Qdrant с боевым корпусом, 6 вопросов:
4 с известным ответом в базе, 2 заведомо вне базы) дала следующее.

*Честный отказ грейдер не покупает.* Оба внедоменных вопроса («ставка
налога на прибыль», «отпуск по уходу за ребёнком») отсекаются **порогом
близости 0,55 ещё до грейдера**: поиск возвращает ноль фрагментов, и
`grade_chunks` отдаёт пустой список, вообще не вызывая модель. Приписывать
эти отказы грейдеру нельзя — их сделал порог. Вопросов, где грейдер
самостоятельно дал бы отказ, в замере не нашлось: на «кто выдаёт
наряд-допуск» он оставил 3 фрагмента из 5, на «как часто проводится СОУТ» —
1 из 5, то есть отказа не дал ни там, ни там.

*Зато он теряет ответы.* С отсевом «частично относящихся» ответ пропал в
2 случаях из 4, устойчиво от прогона к прогону: на вопросе о сроке
расследования несчастного случая ответ лежал в 4-м фрагменте, а грейдер
оставил только 2-й; на вопросе о сроке подачи заявки на проверку знаний
ответ был во 2-м, оставлен 1-й. В обоих случаях фрагмент с ответом получил
вердикт «частично» — то есть искомое живёт именно в той категории, которую
отсев выбрасывает.

*С `keep_partial=True` он безвреден и бесполезен:* 4 ответа из 4 на месте,
но выдача не изменилась ни на одном вопросе — грейдер просто пропустил всё
насквозь, потратив время.

Отсюда `grading_enabled = False` и `grading_keep_partial = True`: если
грейдинг всё же включат, он не должен резать ответы.

Поштучный порог вместо грейдера тоже не годится, и по той же причине:
счета внутри одной выдачи почти плоские, диапазоны релевантных и
посторонних фрагментов пересекаются, точки отсечения не существует.
Порог осмыслен только как ответ на вопрос «есть ли в базе хоть что-то» —
и в этой роли он уже работает.

**Три ловушки структурированного вывода, проверенные запуском.**

1. Поле вердикта обязано быть перечислением. С обычной строкой модель
   наполняет его отсебятиной — в замерах приходили значения «помогает» и
   «helpful» вместо трёх заданных градаций. Описание поля в схеме
   ограничением не является; `Literal` превращается в ``enum`` и включает
   ограниченное декодирование.
2. Длина массива вердиктов должна равняться фактическому числу фрагментов.
   Если зафиксировать её в схеме, грамматика **допишет недостающие**: на
   трёх фрагментах со схемой из пяти элементов вернулось пять вердиктов.
3. Схема должна быть компактной. Выходной токен стоит примерно как
   пятнадцать входных (генерация 11–16 ток/с против чтения промпта
   150–250 ток/с), поэтому короткие коды вердиктов вместо объектов с
   номерами экономят около 7 с на вызов при совпадении решений в 51 случае
   из 60.

Оценка идёт **одним вызовом на всю выдачу**, а не по фрагменту: батч даёт
72 % совпадения с ручной разметкой против 62 % поштучно. Поштучный режим не
видит других кандидатов и ставит всем подряд «частично».
"""

from __future__ import annotations

import logging
from typing import Literal

from pydantic import BaseModel, Field

logger = logging.getLogger(__name__)

#: Коды вердиктов. Короткие ради экономии выходных токенов.
RELEVANT = "Р"
PARTIAL = "Ч"
IRRELEVANT = "Н"

Verdict = Literal["Р", "Ч", "Н"]


class GradeResult(BaseModel):
    """Вердикты по фрагментам в порядке их предъявления.

    Args:
        v: Коды вердиктов: ``Р`` — релевантен, ``Ч`` — частично,
            ``Н`` — нерелевантен. Длина списка обязана совпадать с числом
            предъявленных фрагментов.
    """

    v: list[Verdict] = Field(description="вердикты по фрагментам по порядку")


GRADE_PROMPT = """Ты отбираешь фрагменты регламентов для ответа на вопрос.

Оцени каждый фрагмент по порядку одним кодом:
Р — содержит сведения, из которых можно взять часть ответа;
Ч — по теме вопроса, но прямого ответа не содержит;
Н — не относится к вопросу.

Верни ровно {count} кодов в том же порядке, в каком даны фрагменты."""


def _format_chunks(items: list[dict], snippet_chars: int) -> str:
    """Готовит перечень фрагментов для грейдера.

    Args:
        items: Цитаты в формате `to_citation(...).to_dict()`.
        snippet_chars: Сколько символов фрагмента показывать. Полный текст
            грейдеру не нужен: он решает про тему, а не про формулировку,
            а каждый лишний символ — это входные токены.

    Returns:
        str: Пронумерованный перечень фрагментов.
    """
    return "\n\n".join(
        f"[{n}] {(item.get('text') or item.get('snippet') or '')[:snippet_chars]}"
        for n, item in enumerate(items, 1)
    )


async def grade_chunks(
    model,
    question: str,
    items: list[dict],
    *,
    keep_partial: bool = True,
    snippet_chars: int = 400,
) -> list[dict] | None:
    """Отсеивает фрагменты, не относящиеся к вопросу.

    Args:
        model: Клиент модели. Нужен доступ к `raw` для структурированного
            вывода, поэтому сюда передаётся `OllamaClient`, а не голый
            langchain-клиент.
        question: Вопрос пользователя.
        items: Цитаты после поиска.
        keep_partial: Оставлять ли фрагменты с вердиктом «частично».
            По умолчанию да. Замер показал, что искомое часто попадает
            именно в эту категорию: ответ терялся в 2 случаях из 4, и оба
            раза нужный фрагмент был помечен «частично».
        snippet_chars: Длина показываемого фрагмента.

    Returns:
        list[dict] | None: Отобранные цитаты, либо ``None``, если грейдинг
        не удался. ``None`` означает «оставить всё как было»: сбой грейдера
        не должен ни ронять запрос, ни втихую урезать выдачу.
    """
    if not items:
        return []

    from langchain_core.messages import HumanMessage, SystemMessage

    try:
        structured = model.raw.with_structured_output(GradeResult)
        result = await structured.ainvoke(
            [
                SystemMessage(GRADE_PROMPT.format(count=len(items))),
                HumanMessage(
                    f"ВОПРОС: {question}\n\n"
                    f"ФРАГМЕНТЫ:\n{_format_chunks(items, snippet_chars)}"
                ),
            ]
        )
    except Exception as exc:
        # Ловится всё: разбор структурированного вывода, сеть и сама Ollama
        # падают разными классами исключений, а последствие у них одно —
        # грейдинга не было.
        logger.warning("грейдинг не выполнен, выдача остаётся как есть: %s", exc)
        return None

    verdicts = list(getattr(result, "v", []) or [])
    if len(verdicts) != len(items):
        # Ограниченное декодирование умеет дописывать недостающие элементы,
        # поэтому соответствие «вердикт — фрагмент» по порядку нельзя брать
        # на веру. Расхождение длин означает, что соответствие потеряно.
        logger.warning(
            "грейдер вернул %d вердиктов на %d фрагментов — выдача остаётся как есть",
            len(verdicts),
            len(items),
        )
        return None

    allowed = {RELEVANT, PARTIAL} if keep_partial else {RELEVANT}
    kept = [
        item
        for item, verdict in zip(items, verdicts, strict=True)
        if verdict in allowed
    ]

    logger.info(
        "грейдер: из %d фрагментов оставлено %d (вердикты: %s)",
        len(items),
        len(kept),
        "".join(verdicts),
    )
    return kept
