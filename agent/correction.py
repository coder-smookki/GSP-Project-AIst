"""Коррекция запроса, когда поиск ничего не нашёл.

Это урезанная форма Corrective RAG, и урезана она по результатам замеров, а
не из экономии сил.

**Чего здесь намеренно нет: грейдера релевантности на каждый запрос.**
Замерено на qwen3:8b: оценка пяти найденных фрагментов одним вызовом со
структурированным выводом стоит 10,8–23,3 с, тогда как сокращение контекста
с пяти фрагментов до трёх экономит около 9 с. Грейдер тратит больше, чем
экономит, и делает это непредсказуемо — на одном вопросе он оставил все пять
из пяти, на другом выбросил четыре из пяти. Отбором фрагментов занимается
кросс-энкодер (`infrastructure.retrieval.rerank`): та же работа за доли
секунды, потому что это маленькая специализированная модель.

**Что здесь есть: переписывание запроса при неудаче.** Оно вызывается только
когда поиск вернул пусто, то есть примерно никогда на обычных вопросах и
ровно тогда, когда иначе пользователь получил бы отказ. Средняя цена по всем
запросам близка к нулю, а спасает оно ровно тот случай, ради которого
задумано: вопрос задан житейскими словами, а регламент написан канцелярскими.

Ограничение на один круг жёсткое. Второй круг стоит ещё одного вызова модели
и ещё одного поиска, а вероятность, что переписывание сработает со второго
раза, если не сработало с первого, мала.
"""

from __future__ import annotations

import logging

logger = logging.getLogger(__name__)

#: Промпт переписывания.
#:
#: Просим не «улучшить запрос вообще», а перевести его на язык документа:
#: именно рассогласование лексики пользователя и регламента чаще всего и
#: приводит к пустой выдаче.
REWRITE_PROMPT = """Ты помогаешь искать в корпоративной базе регламентов по охране \
труда, промышленной и пожарной безопасности, гражданской обороне.

Поиск по исходному вопросу ничего не нашёл. Перепиши его теми словами, \
которыми пишут в регламентах: официальные термины, отглагольные \
существительные, принятые в документах обороты.

Правила:
- сохрани смысл, не добавляй условий, которых в вопросе не было;
- не задавай встречных вопросов и не объясняй, что делаешь;
- верни ТОЛЬКО переписанный запрос одной строкой.

Вопрос: {question}"""

#: Предел длины переписанного запроса. Больше — значит модель вместо запроса
#: вернула рассуждение, и такой текст в поиск отправлять нельзя.
MAX_REWRITE_CHARS = 300


async def rewrite_query(model, question: str) -> str | None:
    """Переписывает вопрос языком регламентов.

    Args:
        model: Клиент модели с методом ``ainvoke``. Разумно передавать сюда
            лёгкую служебную модель, а не ту, что пишет ответ.
        question: Исходный вопрос пользователя.

    Returns:
        str | None: Переписанный запрос либо ``None``, если переписать не
        удалось или результат непригоден. ``None`` означает «оставить всё
        как есть»: неудача коррекции не должна отменять честный отказ.
    """
    from langchain_core.messages import HumanMessage

    text = question.strip()
    if not text:
        return None

    try:
        answer = await model.ainvoke(
            messages=[HumanMessage(REWRITE_PROMPT.format(question=text))]
        )
    except Exception as exc:
        logger.warning("переписывание запроса не выполнено: %s", exc)
        return None

    rewritten = str(getattr(answer, "content", "") or "").strip().strip('"«»')
    rewritten = rewritten.splitlines()[0].strip() if rewritten else ""

    if not rewritten or len(rewritten) > MAX_REWRITE_CHARS:
        logger.info("переписывание отвергнуто: результат пуст или слишком длинный")
        return None
    if rewritten.casefold() == text.casefold():
        logger.info("переписывание ничего не изменило")
        return None

    logger.info("запрос переписан: %r -> %r", text[:60], rewritten[:60])
    return rewritten
