"""Сверка чисел ответа с контекстом.

Замер на золотом наборе показал, что самая опасная ошибка выглядит так:

    «Регистрация микротравмы проводится в течение 24 часов с момента её
    получения [1].»

Числа «24 часа» в корпусе нет вовсе. Ответ уверенный, оформлен по правилам,
снабжён ссылкой на источник — и потому неотличим от настоящего требования
регламента. Проверить его пользователь не может: ссылка [1] ведёт на
реальный фрагмент, просто этого срока в нём не написано.

Ни грейдер, ни усиление правил промпта такие ответы не убрали: на qwen3:8b
доля верных отказов остаётся 6 из 10 во всех трёх режимах. Значит защита
должна быть не на модели, а рядом с ней — детерминированная, дешёвая и не
зависящая от того, насколько послушна модель.

**Как работает.** Из ответа берутся пары «число + следующее слово» и
сверяются с контекстом. Голое число не годится: цифры 5, 10 и 15 стоят в
номерах пунктов почти каждого документа, и «5 рабочих дней» прошло бы
проверку только потому, что где-то есть пункт 5.2. Пара «5 рабоч» такого
совпадения не даёт.

Проверено на живых запросах: пара ловит и «24 часов», и «5 рабочих дней»,
пропуская при этом настоящее «15 календарных дней» — оно в контексте есть.
"""

from __future__ import annotations

import logging
import re

logger = logging.getLogger(__name__)

#: Число и следующее за ним слово.
_NUMBER_WITH_UNIT = re.compile(r"\b(\d+)\s+([а-я]+)")

#: Маркеры источников: [1], [2] — это не числа ответа.
_CITATION = re.compile(r"\[\d+\]")

#: Сколько букв единицы учитывать при сравнении.
#:
#: Слово берётся не целиком ради падежей: «24 часа» в ответе и «24 часов» в
#: регламенте — одно и то же, а полное совпадение развело бы их. Три буквы, а
#: не пять: русские основы коротки, и на пяти «часа» уже не сходится с
#: «часов». Три покрывают час/часа/часов, дня/дней, год/года/годов. Риск
#: лишнего совпадения мал, потому что сравнивается пара с числом, а не слово
#: само по себе.
_UNIT_PREFIX = 3


def _pairs(text: str) -> set[tuple[str, str]]:
    """Извлекает пары «число + единица».

    Args:
        text: Текст ответа или контекста.

    Returns:
        set[tuple[str, str]]: Пары «число, начало слова единицы».
    """
    normalized = text.lower().replace("ё", "е")
    return {
        (match.group(1), match.group(2)[:_UNIT_PREFIX])
        for match in _NUMBER_WITH_UNIT.finditer(normalized)
    }


def unsupported_numbers(answer: str, context: str) -> list[str]:
    """Находит числа ответа, которых нет в контексте.

    Args:
        answer: Текст ответа модели.
        context: Склеенный текст фрагментов, отданных модели.

    Returns:
        list[str]: Пары «число единица», не найденные в контексте, по
        порядку. Пустой список означает, что все числа ответа подтверждены.
    """
    if not answer or not context:
        return []

    body = _CITATION.sub(" ", answer)
    missing = _pairs(body) - _pairs(context)
    return sorted(f"{number} {unit}" for number, unit in missing)


#: Приписка к ответу, в котором нашлись неподтверждённые числа.
WARNING_TEMPLATE = (
    "\n\n> ⚠️ Проверьте по первоисточнику: в найденных выдержках не нашлось "
    "подтверждения для {values}. Остальная часть ответа опирается на выдержки."
)


def annotate(answer: str, context: str) -> str:
    """Помечает ответ, если в нём есть неподтверждённые числа.

    Предупреждение, а не отказ. Ответ может быть верным по существу, а число
    попасть в него из соседнего пункта, который в контекст не вошёл; стирать
    из-за этого готовый ответ значит менять одну ошибку на другую. Задача —
    чтобы человек не принял неподтверждённый срок за требование регламента.

    Args:
        answer: Текст ответа модели.
        context: Склеенный текст фрагментов, отданных модели.

    Returns:
        str: Ответ, при необходимости дополненный предупреждением.
    """
    missing = unsupported_numbers(answer, context)
    if not missing:
        return answer

    logger.warning(
        "в ответе есть числа, которых нет в контексте: %s", ", ".join(missing)
    )
    values = ", ".join(f"«{value}»" for value in missing)
    return answer + WARNING_TEMPLATE.format(values=values)
