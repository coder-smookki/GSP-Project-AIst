"""Регулярные выражения разбора регламентов — единая точка правды.

Все выражения якорные: срабатывают только в начале абзаца или после явного
разделителя. Это осознанное ограничение — в тексте регламентов полно чисел,
похожих на номера пунктов (даты «12.02.1998», номера законов «№ 28-ФЗ»,
диапазоны «п. 3.2.8»), и неякорный поиск даёт ложные разрезы атомов.

Выражения проверяются тестом на реальном корпусе: он падает, если появятся
ложные срабатывания на известных ловушках.
"""

from __future__ import annotations

import re
from typing import Final

#: Номер пункта в начале абзаца: ``4.1.2.`` или ``4.1.2)``.
#:
#: Ведущая точка опциональна: конвертер источника срезает первую цифру у
#: первого пункта раздела, превращая ``1.1.`` в ``.1.`` — такие номера
#: достраиваются номером раздела (см. `restore_clause`).
CLAUSE_HEAD: Final[re.Pattern[str]] = re.compile(
    r"^\s*(?P<truncated>\.)?(?P<clause>\d{1,2}(?:\.\d{1,3}){0,4})\s*[.)]\s+"
)

#: Номер пункта, приклеенный к концу предыдущего предложения:
#: ``…являются:.2.1. Обучение…``. Тот же дефект конвертера, но в середине
#: абзаца. Ищем только после ``:`` или ``.``, иначе ловим дроби и даты.
CLAUSE_GLUED: Final[re.Pattern[str]] = re.compile(
    r"(?<=[:.])\s*(?P<truncated>\.)(?P<clause>\d{1,2}(?:\.\d{1,3}){0,3})\.\s+"
)

#: Заголовок раздела: ``4. Порядок проведения``. Ограничение длины
#: намеренное — без него в заголовки попадают абзацы, начинающиеся с числа.
SECTION_HEAD: Final[re.Pattern[str]] = re.compile(
    r"^\s*(?P<no>\d{1,2})\s*[.)]\s*(?P<title>.{2,190}?)\s*$"
)

#: Плейсхолдер анонимизации: ``[ОРГАНИЗАЦИЯ_12]``, ``[АДРЕС_5]``.
PLACEHOLDER: Final[re.Pattern[str]] = re.compile(r"\[[A-ZА-ЯЁ]+(?:_[A-ZА-ЯЁ]+)*_\d+\]")

#: Строка словаря сокращений: ``[ОРГАНИЗАЦИЯ_18] — пожарная безопасность``.
#:
#: Ровно этот дефект анонимайзера и есть канал восстановления: заменена
#: аббревиатура, но расшифровка рядом уцелела. Разделителем бывает тире
#: любого начертания или дефис.
GLOSSARY_LINE: Final[re.Pattern[str]] = re.compile(
    r"(?P<key>\[[A-ZА-ЯЁ]+(?:_[A-ZА-ЯЁ]+)*_\d+\])\s*[—–-]\s*(?P<value>[^;.]{3,160})"
)

#: Обратный порядок строки словаря: ``Общество — [ОРГАНИЗАЦИЯ_1]``.
#:
#: Анонимайзер заменял и левую, и правую часть определения, поэтому канал
#: восстановления двусторонний. Здесь метка стоит справа, а слева — термин,
#: которым документ и называет скрытую сущность; подставлять надо именно его.
GLOSSARY_LINE_REVERSED: Final[re.Pattern[str]] = re.compile(
    r"(?<![\w\]])(?P<value>[А-ЯЁ][А-Яа-яЁё][А-Яа-яЁё\s-]{1,58}?)\s*[—–]\s*"
    r"(?P<key>\[[A-ZА-ЯЁ]+(?:_[A-ZА-ЯЁ]+)*_\d+\])"
)

#: Строка словаря для уцелевших аббревиатур: ``ЛВЖ — легковоспламеняющаяся…``.
#: Нужна, чтобы расширять запрос синонимами, а не только чинить плейсхолдеры.
ABBREVIATION_LINE: Final[re.Pattern[str]] = re.compile(
    r"(?<![\w\]])(?P<key>[А-ЯЁ]{2,10}(?:иОБТ|иМП)?)\s*[—–-]\s*(?P<value>[^;.]{3,160})"
)

#: Код документа: ``Р-У2-59``, ``P-U2-23``. Латиница допускается: имена
#: файлов транслитерированы.
DOC_CODE: Final[re.Pattern[str]] = re.compile(
    r"\b(?P<code>[РP]\s?[-–]\s?[АAУY]\d\s?[-–]\s?\d{1,3})\b"
)

#: Порядковый номер в названии статьи API: ``(20) Регламент …``.
API_TITLE_NO: Final[re.Pattern[str]] = re.compile(
    r"^\s*\((?P<no>\d{1,3})\)\s*(?P<title>.+)$"
)

#: Дата в тексте — маркер ложного срабатывания номера пункта.
DATE_LIKE: Final[re.Pattern[str]] = re.compile(r"\b\d{2}\.\d{2}\.\d{4}\b")

#: Мусор XML, просачивающийся при некорректной выгрузке .docx.
XML_JUNK: Final[re.Pattern[str]] = re.compile(r"</?w:[a-zA-Z]+[^>]*>")

#: Ссылка на таблицу или приложение без содержимого — маркер табличной зоны.
TABLE_REF: Final[re.Pattern[str]] = re.compile(
    r"\b(?:табли\w+|приложени\w+)\s*(?:№\s*)?\d{1,2}\b", re.IGNORECASE
)

#: Заголовки разделов -> тип раздела. Порядок важен: правила проверяются
#: сверху вниз, первое совпадение выигрывает.
_SECTION_TYPE_RULES: Final[tuple[tuple[re.Pattern[str], str], ...]] = (
    # ТОЧНОЕ совпадение целого заголовка, а не вхождение подстроки.
    # Правило r"содержани" ловило не оглавление, а содержательные разделы
    # регламентов: «Порядок содержания территории, здания и помещений»,
    # «Порядок содержания помещений», «Содержание рабочего места».
    # Замер по корпусу: выбрасывалось 6 разделов, 61 атом, 19134 символа
    # в 5 документах из 20 — на вопрос, ответ на который в базе ЕСТЬ,
    # пользователь получал отказ. Настоящее оглавление при этом лежит
    # в <nav> и отбрасывается парсером ещё раньше.
    (re.compile(r"^\s*(оглавлени\w*|содержание)\s*$", re.I), "soderzhanie"),
    (re.compile(r"назначени|область примен", re.I), "naznachenie"),
    (re.compile(r"термин|определени|сокращени", re.I), "terminy"),
    (re.compile(r"нормативн|ссылк", re.I), "normativnye_ssylki"),
    (re.compile(r"ответственн|контрол", re.I), "otvetstvennost"),
    (re.compile(r"приложени", re.I), "prilozhenie"),
    (re.compile(r"общие|основные положени", re.I), "obshchie"),
    (
        re.compile(r"порядок|процедур|провед|организац|требовани|обучени", re.I),
        "procedura",
    ),
)


def classify_section(title: str) -> str:
    """Определяет тип раздела по его заголовку.

    Args:
        title: Заголовок раздела без номера, например ``Термины и сокращения``.

    Returns:
        str: Значение `SectionType`; ``prochee``, если ни одно правило
        не сработало.
    """
    for pattern, section_type in _SECTION_TYPE_RULES:
        if pattern.search(title):
            return section_type
    return "prochee"


def restore_clause(clause: str, *, truncated: bool, section_no: str) -> str:
    """Достраивает номер пункта, у которого конвертер срезал первую цифру.

    Источник отдаёт первый пункт раздела как ``.1.`` вместо ``1.1.``.
    Восстановление возможно, потому что раздел известен из заголовка `<h2>`.

    Args:
        clause: Номер пункта как он найден в тексте, например ``1`` или ``2.1``.
        truncated: Признак срезанной первой цифры (в тексте номер начинался
            с точки).
        section_no: Номер текущего раздела, например ``4``.

    Returns:
        str: Полный номер пункта, например ``4.1`` или ``4.2.1``. Если
        восстановить нельзя (раздел неизвестен), номер возвращается как есть.
    """
    if not section_no:
        return clause

    if truncated:
        return f"{section_no}.{clause}"

    # Двузначные разделы: конвертер срезает ПЕРВУЮ ЦИФРУ, и у номера
    # «12.1.» ведущая точка не появляется — получается «2.1.», признак
    # truncated равен False, и номер молча уходит в индекс неверным.
    # Хуже того, пункт «2.1» в этих документах существует и означает другое
    # (раздел 2 — термины), то есть цитата указывает на реальный чужой
    # пункт. Достраиваем по сверке с номером раздела: если номер не
    # начинается с раздела, но раздел оканчивается на первый компонент
    # номера, значит срезана именно первая цифра.
    head, _, tail = clause.partition(".")
    if head != section_no and len(section_no) > 1 and section_no.endswith(head):
        return f"{section_no}.{tail}" if tail else section_no
    return clause


def is_false_clause(text: str, match: re.Match[str]) -> bool:
    """Проверяет, не является ли найденный «номер пункта» частью даты.

    Args:
        text: Текст абзаца, в котором выполнялся поиск.
        match: Совпадение `CLAUSE_HEAD` или `CLAUSE_GLUED`.

    Returns:
        bool: ``True``, если совпадение попадает внутрь даты вида
        ``12.02.1998`` и потому не является номером пункта.
    """
    start, end = match.span("clause")
    return any(d.start() <= start and end <= d.end() for d in DATE_LIKE.finditer(text))
